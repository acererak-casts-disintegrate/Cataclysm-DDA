#!/usr/bin/env python3
"""Build the British English catalogue lang/po/en_GB.po from the game's
translation template (lang/po/cataclysm-dda.pot).

English is the game's source language, and the game shows the source text for
any string a catalogue leaves out. So en_GB.po holds only the strings whose
British form differs: American spellings from spelling.tsv, vocabulary from
vocabulary.tsv, with the phrases in keep.txt left alone. Markup (<color_red>,
<npcname>), printf placeholders (%s, %1$d) and {braced} fields are never
changed.

Usage: lang/en_GB/make_en_GB_po.py [--check] [template.pot] [output.po]
Run lang/update_en_GB.sh instead to regenerate the template first.
"""

import argparse
import os
import re
import sys

import polib

HERE = os.path.dirname(os.path.abspath(__file__))

# Spans that must pass through untouched.
PROTECTED = re.compile(
    r'</?[A-Za-z_!][^<>\s]*>'                      # markup tags
    r'|%(?:\d+\$)?[-+#0]*\d*(?:\.\d+)?[a-zA-Z%]'   # printf placeholders
    r'|\{[^{}]*\}'                                 # braced fields
)
# A run of letters (any script, so "Honoré" stays one word) not joined to
# digits or underscores, so identifiers such as armor_portion are left alone.
WORD = re.compile(r"(?<!\w)[^\W\d_]+(?!\w)")


def read_pairs(name):
    pairs = []
    with open(os.path.join(HERE, name), encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            if not line or line.startswith('#'):
                continue
            us, uk = line.split('\t')
            pairs.append((us, uk))
    return pairs


def read_lines(name):
    with open(os.path.join(HERE, name), encoding='utf-8') as f:
        return [line.rstrip('\n') for line in f
                if line.strip() and not line.startswith('#')]


def match_case(original, replacement, key=''):
    """Give replacement the capitalisation of original. A capital that the
    American key itself has ("French fries") does not carry over."""
    if len(original) > 1 and original.isupper():
        return replacement.upper()
    if original[:1].isupper() and not key[:1].isupper():
        return replacement[:1].upper() + replacement[1:]
    return replacement


class Converter:
    def __init__(self):
        self.spelling = {us.lower(): uk for us, uk in read_pairs('spelling.tsv')}
        vocab = sorted(read_pairs('vocabulary.tsv'), key=lambda p: -len(p[0]))
        self.vocab = {us.lower(): (us, uk) for us, uk in vocab}
        self.vocab_re = re.compile(
            r'\b(?:' + '|'.join(re.escape(us) for us, _ in vocab) + r')\b',
            re.IGNORECASE)
        keep = sorted(read_lines('keep.txt'), key=len, reverse=True)
        # A kept phrase also covers its plural and possessive (health meters).
        self.keep_re = re.compile(
            r'\b(?:' + '|'.join(re.escape(k) for k in keep) + r")(?:e?s|'s)?\b",
            re.IGNORECASE)

    def convert(self, text):
        saved = []

        def mask(match):
            saved.append(match.group(0))
            return '\x00%d\x00' % (len(saved) - 1)

        out = PROTECTED.sub(mask, text)
        out = self.keep_re.sub(mask, out)
        out = self.vocab_re.sub(self._vocab_sub, out)
        out = WORD.sub(
            lambda m: match_case(m.group(0), self.spelling[m.group(0).lower()])
            if m.group(0).lower() in self.spelling else m.group(0), out)
        return re.sub('\x00(\\d+)\x00', lambda m: saved[int(m.group(1))], out)

    def _vocab_sub(self, match):
        us, uk = self.vocab[match.group(0).lower()]
        return match_case(match.group(0), uk, us)


def build(pot):
    conv = Converter()
    po = polib.POFile(wrapwidth=0)
    po.metadata = {
        'Project-Id-Version': pot.metadata.get('Project-Id-Version', 'cataclysm-dda'),
        'Language': 'en_GB',
        'MIME-Version': '1.0',
        'Content-Type': 'text/plain; charset=UTF-8',
        'Content-Transfer-Encoding': '8bit',
        'Plural-Forms': 'nplurals=2; plural=(n != 1);',
    }
    po.header = ('British English for this fork of Cataclysm: Dark Days Ahead.\n'
                 'Generated by lang/en_GB/make_en_GB_po.py; do not edit by hand.')
    for entry in pot:
        if entry.obsolete or not entry.msgid:
            continue
        single = conv.convert(entry.msgid)
        if entry.msgid_plural:
            plural = conv.convert(entry.msgid_plural)
            if single == entry.msgid and plural == entry.msgid_plural:
                continue
            new = polib.POEntry(msgctxt=entry.msgctxt, msgid=entry.msgid,
                                msgid_plural=entry.msgid_plural,
                                msgstr_plural={0: single, 1: plural},
                                flags=list(entry.flags))
        else:
            if single == entry.msgid:
                continue
            new = polib.POEntry(msgctxt=entry.msgctxt, msgid=entry.msgid,
                                msgstr=single, flags=list(entry.flags))
        po.append(new)
    return po


def contents(po):
    """The translations in po, ignoring order and formatting."""
    return {(e.msgctxt, e.msgid, e.msgid_plural): (e.msgstr, tuple(sorted(e.msgstr_plural.items())))
            for e in po if not e.obsolete and e.msgid}


def main():
    root = os.path.dirname(os.path.dirname(HERE))
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('pot', nargs='?',
                        default=os.path.join(root, 'lang', 'po', 'cataclysm-dda.pot'),
                        help='translation template (default: lang/po/cataclysm-dda.pot)')
    parser.add_argument('po', nargs='?',
                        default=os.path.join(root, 'lang', 'po', 'en_GB.po'),
                        help='catalogue to write (default: lang/po/en_GB.po)')
    parser.add_argument('--check', action='store_true',
                        help='write nothing; exit with status 1 if the catalogue is out of date')
    args = parser.parse_args()

    pot = polib.pofile(args.pot, wrapwidth=0)
    po = build(pot)
    name = os.path.relpath(args.po, root)
    if args.check:
        new = contents(po)
        old = contents(polib.pofile(args.po)) if os.path.exists(args.po) else {}
        added = new.keys() - old.keys()
        removed = old.keys() - new.keys()
        changed = {k for k in new.keys() & old.keys() if new[k] != old[k]}
        if not (added or removed or changed):
            print('%s is up to date (%d strings)' % (name, len(new)))
            return 0
        print('%s is out of date: %d strings to add, %d to remove, %d to change' % (
            name, len(added), len(removed), len(changed)))
        for key in sorted(added | changed, key=lambda k: (k[1], k[0] or ''))[:20]:
            print('  %r' % key[1][:100])
        return 1
    po.save(args.po)
    print('%s: %d of %d strings differ in British English' % (name, len(po), len(pot)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
